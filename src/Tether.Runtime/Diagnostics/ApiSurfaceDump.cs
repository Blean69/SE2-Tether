using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Runtime.Loader;
using System.Text;
using Tether.Diagnostics;

namespace Tether.Runtime.Diagnostics;

/// <summary>
/// Writes the names and signatures of the game's types in chosen namespaces to text files, one per
/// assembly. This is metadata only: no method bodies, no IL. It helps Phase 0 map Keen's networking seam,
/// and the output is sorted so dumps from two game builds can be diffed to spot breaking changes.
/// </summary>
/// <remarks>
/// The dumps describe Keen's code, so they stay on your machine and are git-ignored (api-dumps/).
/// Write findings up in our own words in docs/engine-map.md.
/// </remarks>
internal static class ApiSurfaceDump
{
    private const BindingFlags All = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

    public static int Write(string directory, IReadOnlyList<string> namespaces, ITetherLog log)
    {
        Directory.CreateDirectory(directory);
        LoadGameAssemblies(log);

        var total = 0;
        foreach (var assembly in AppDomain.CurrentDomain.GetAssemblies().OrderBy(a => a.GetName().Name, StringComparer.Ordinal))
        {
            var name = assembly.GetName().Name ?? "unknown";
            if (!IsGameAssembly(name))
            {
                continue;
            }

            // Reading a type's name can itself throw when the type references an assembly the game doesn't
            // ship (editor-only ones, for instance), so every lookup is guarded and such types are skipped.
            var types = GetTypesSafely(assembly)
                .Select(t => (Type: t, Namespace: Try<string?>(() => t.Namespace, null), FullName: Try<string?>(() => t.FullName, null)))
                .Where(x => x.FullName is not null && x.Namespace is { } ns && namespaces.Any(prefix => ns == prefix || ns.StartsWith(prefix + ".", StringComparison.Ordinal)))
                .OrderBy(x => x.FullName, StringComparer.Ordinal)
                .Select(x => x.Type)
                .ToList();
            if (types.Count == 0)
            {
                continue;
            }

            var builder = new StringBuilder();
            builder.AppendLine($"# {name} {assembly.GetName().Version}");
            builder.AppendLine($"# Namespaces: {string.Join(", ", namespaces)}");
            builder.AppendLine("# Generated by Tether -tether:dump-api. Metadata only; keep local.");
            var skipped = 0;
            foreach (var type in types)
            {
                var start = builder.Length;
                try
                {
                    AppendType(builder, type);
                }
                catch (Exception ex)
                {
                    builder.Length = start;
                    builder.AppendLine().AppendLine($"# skipped {Try(() => type.FullName, "?")}: {ex.GetType().Name}");
                    skipped++;
                }
            }

            if (skipped > 0)
            {
                log.Debug($"API dump: {name}: skipped {skipped} type(s) that could not be inspected.");
            }

            File.WriteAllText(Path.Combine(directory, name + ".txt"), builder.ToString());
            total += types.Count;
        }

        return total;
    }

    private static bool IsGameAssembly(string name) =>
        name.StartsWith("VRage.", StringComparison.Ordinal)
        || name.StartsWith("Game2.", StringComparison.Ordinal)
        || name == "SpaceEngineers2";

    /// <summary>Loads managed game assemblies that haven't been loaded yet, so the dump is complete.</summary>
    private static void LoadGameAssemblies(ITetherLog log)
    {
        var loaded = AppDomain.CurrentDomain.GetAssemblies().Select(a => a.GetName().Name).ToHashSet(StringComparer.Ordinal);
        foreach (var path in Directory.EnumerateFiles(AppContext.BaseDirectory, "*.dll"))
        {
            var fileName = Path.GetFileNameWithoutExtension(path);
            if (!IsGameAssembly(fileName) || loaded.Contains(fileName) || fileName.Contains("Native", StringComparison.Ordinal))
            {
                continue;
            }

            try
            {
                AssemblyLoadContext.Default.LoadFromAssemblyName(AssemblyName.GetAssemblyName(path));
            }
            catch (BadImageFormatException)
            {
                // A native DLL with a managed-looking name.
            }
            catch (Exception ex)
            {
                log.Debug($"API dump: could not load {fileName}: {ex.Message}");
            }
        }
    }

    private static IEnumerable<Type> GetTypesSafely(Assembly assembly)
    {
        try
        {
            return assembly.GetTypes();
        }
        catch (ReflectionTypeLoadException ex)
        {
            return ex.Types.Where(t => t is not null)!;
        }
    }

    private static void AppendType(StringBuilder builder, Type type)
    {
        builder.AppendLine();
        var kind = type.IsInterface ? "interface"
            : type.IsEnum ? "enum"
            : type.IsValueType ? "struct"
            : type.IsAbstract && type.IsSealed ? "static class"
            : type.IsAbstract ? "abstract class"
            : type.IsSealed ? "sealed class"
            : "class";
        var bases = new List<string>();
        if (type.BaseType is { } baseType && baseType != typeof(object) && baseType != typeof(ValueType) && baseType != typeof(Enum))
        {
            bases.Add(Name(baseType));
        }

        bases.AddRange(Try(() => type.GetInterfaces(), Type.EmptyTypes).Select(Name).OrderBy(n => n, StringComparer.Ordinal));
        builder.AppendLine($"{Visibility(type)} {kind} {Name(type)}{(bases.Count > 0 ? " : " + string.Join(", ", bases) : string.Empty)}");

        if (type.IsEnum)
        {
            foreach (var value in Try(() => Enum.GetNames(type), Array.Empty<string>()))
            {
                builder.AppendLine($"    {value}");
            }

            return;
        }

        var lines = new List<string>();
        foreach (var member in Try(() => type.GetMembers(All), Array.Empty<MemberInfo>()))
        {
            var line = Try(() => Describe(member), null);
            if (line is not null)
            {
                lines.Add("    " + line);
            }
        }

        lines.Sort(StringComparer.Ordinal);
        foreach (var line in lines)
        {
            builder.AppendLine(line);
        }
    }

    private static string? Describe(MemberInfo member) => member switch
    {
        FieldInfo f when !f.Name.Contains('<') => $"field  {Visibility(f)}{(f.IsStatic ? " static" : string.Empty)} {Name(f.FieldType)} {f.Name}",
        PropertyInfo p => $"prop   {Name(p.PropertyType)} {p.Name} {{{(p.GetMethod is not null ? " " + Visibility(p.GetMethod) + " get;" : string.Empty)}{(p.SetMethod is not null ? " " + Visibility(p.SetMethod) + " set;" : string.Empty)} }}",
        EventInfo e => $"event  {Name(e.EventHandlerType!)} {e.Name}",
        ConstructorInfo c => $"ctor   {Visibility(c)}{(c.IsStatic ? " static" : string.Empty)} ({Parameters(c)})",
        MethodInfo m when !m.IsSpecialName => $"method {Visibility(m)}{(m.IsStatic ? " static" : string.Empty)}{(m.IsAbstract ? " abstract" : m.IsVirtual && !m.IsFinal ? " virtual" : string.Empty)} {Name(m.ReturnType)} {m.Name}{(m.IsGenericMethodDefinition ? "<" + string.Join(", ", m.GetGenericArguments().Select(Name)) + ">" : string.Empty)}({Parameters(m)})",
        Type nested => $"nested {Name(nested)}",
        _ => null,
    };

    private static string Parameters(MethodBase method) =>
        string.Join(", ", method.GetParameters().Select(p => $"{(p.IsOut ? "out " : p.ParameterType.IsByRef ? "ref " : string.Empty)}{Name(p.ParameterType)} {p.Name}"));

    private static string Name(Type type)
    {
        if (type.IsByRef || type.IsPointer || type.IsArray)
        {
            var element = Name(type.GetElementType()!);
            return type.IsArray ? element + "[]" : type.IsPointer ? element + "*" : element;
        }

        var name = type.IsNested && !type.IsGenericParameter ? Name(type.DeclaringType!) + "." + type.Name : type.FullName ?? type.Name;
        if (!type.IsGenericType)
        {
            return name;
        }

        var tick = name.IndexOf('`');
        var stem = tick >= 0 ? name.Substring(0, tick) : name;
        return $"{stem}<{string.Join(", ", type.GetGenericArguments().Select(Name))}>";
    }

    private static string Visibility(Type type) =>
        type.IsPublic || type.IsNestedPublic ? "public" : type.IsNestedFamily ? "protected" : "internal";

    private static string Visibility(MethodBase method) =>
        method.IsPublic ? "public" : method.IsFamily ? "protected" : method.IsAssembly ? "internal" : method.IsFamilyOrAssembly ? "protected internal" : "private";

    private static string Visibility(FieldInfo field) =>
        field.IsPublic ? "public" : field.IsFamily ? "protected" : field.IsAssembly ? "internal" : field.IsFamilyOrAssembly ? "protected internal" : "private";

    private static T Try<T>(Func<T> func, T fallback)
    {
        try
        {
            return func();
        }
        catch
        {
            return fallback;
        }
    }
}
